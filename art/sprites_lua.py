"""Generate the sprite block of frog.lua from the pixel art (frog outline + interior mask + lily pad)."""
import math, re, sys
import gen5, gen7, os
sys_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'sim')
import sys as _s; _s.path.insert(0, sys_path)
from fonts import FONTS

def exterior(rows):
    H, W = len(rows), len(rows[0]); out = [[False]*W for _ in range(H)]
    st = [(x, y) for x in range(W) for y in (0, H-1)] + [(x, y) for y in range(H) for x in (0, W-1)]
    while st:
        x, y = st.pop()
        if 0 <= x < W and 0 <= y < H and not out[y][x] and rows[y][x] != '#':
            out[y][x] = True; st += [(x+1,y),(x-1,y),(x,y+1),(x,y-1)]
    return out

def lily_pad(w=63, h=9):
    g = [['.']*w for _ in range(h)]; cx, cy, rx, ry = (w-1)/2, (h-1)/2, (w-1)/2, (h-1)/2
    for k in range(3600):
        t = k/1800*math.pi; x = round(cx + rx*math.cos(t)); y = round(cy + ry*math.sin(t))
        g[y][x] = '#'
    # notch on the front right: a V cut from the rim towards the centre
    for i in range(0, 5):
        x = round(cx + 18 - i*2.6); y = h - 1 - i
        for xx in range(x-1, x+3 + i//2):
            if 0 <= xx < w and g[y][xx] == '#' and y == h-1: g[y][xx] = '.'
    for i in range(4):
        g[h-1-i][round(cx + 15 - i*2.2)] = '#'; g[h-1-i][round(cx + 21 - i*1.4)] = '#'
    for i in range(1, 4): g[h-1][round(cx + 15) + i] = '.'
    # veins: dotted radial lines from the centre
    for ang in (200, 235, 305, 340):
        for r in range(6, 26, 4):
            t = math.radians(ang); x = round(cx + r*math.cos(t)); y = round(cy - 0.5 + r*math.sin(t)*ry/rx)
            if 0 <= y < h and 0 <= x < w and g[y][x] == '.': g[y][x] = '#'
    return [''.join(r) for r in g]

def lua_table(name, rows):
    return f'local {name} = {{\n' + ''.join(f'  "{r}",\n' for r in rows) + '}\n'

if __name__ == '__main__':
    frog = gen7.build()
    # mask = everything between the frog's leftmost and rightmost pixel per row, plus a 1 px halo,
    # so the lily pad never shows through the frog (the outline itself is open at the belly and toes)
    mask = []
    for r in frog:
        a, b = r.find('#'), r.rfind('#')
        mask.append(''.join('#' if a >= 0 and a - 1 <= x <= b + 1 else '.' for x in range(len(r))))
    pad = lily_pad()
    chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!-* '
    gw = lambda f: '{ ' + ', '.join(f'["{c}"] = {FONTS[f].width(c)}' for c in chars) + ' }'
    metrics = ('-- glyph widths of the EdgeTX 128x64 fonts (ink spans the whole glyph for these characters)\n'
               f'local GLYPH_W = {{\n  MID = {gw("MID")},\n  SML = {gw("SML")},\n}}\n\n')
    block = ('-- SPRITES BEGIN (generated by art/sprites_lua.py, edit the art there)\n' + metrics
             + lua_table('FROG', frog)
             + '-- SPRITES END')
    p = sys.argv[1]; s = open(p).read()
    s = re.sub(r'-- SPRITES BEGIN.*?-- SPRITES END', lambda m: block, s, flags=re.S)
    open(p, 'w').write(s)
    print('\n'.join(pad)); print(); print('\n'.join(mask))
