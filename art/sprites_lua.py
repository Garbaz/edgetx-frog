"""Generate the sprite block of frog.lua (between SPRITES BEGIN / END) from the pixel art in this directory."""
import os, re, sys
import faces
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'sim'))
from fonts import FONTS

def block():
    chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!-* '
    gw = lambda f: '{ ' + ', '.join(f'["{c}"] = {FONTS[f].width(c)}' for c in chars) + ' }'
    base = faces.base()
    return ('-- SPRITES BEGIN (generated by art/sprites_lua.py, edit the art there)\n'
            '-- glyph widths of the EdgeTX 128x64 fonts (ink spans the whole glyph for these characters)\n'
            f'local GLYPH_W = {{\n  MID = {gw("MID")},\n  SML = {gw("SML")},\n}}\n\n'
            '-- frog without pupils and mouth, as runs: x, y, width (repeated)\n'
            'local FROG = ' + faces.lua_runs(faces.points(base)) + '\n\n'
            '-- frog silhouette (row spans, 1 px halo): erased before the frog is drawn, hides what is behind it\n'
            'local FROG_MASK = ' + faces.lua_runs([(x, y) for y, r in enumerate(base) if '#' in r
                                                   for x in range(max(0, r.find('#') - 1), min(len(r), r.rfind('#') + 2))]) + '\n\n'
            '-- face parts drawn on top of the frog (both halves)\n'
            'local FACE = {\n  eyes = {\n'
            + ''.join(f'    {n} = {faces.lua_runs(faces.mirror(p))},\n' for n, p in faces.EYES.items())
            + ''.join(f'    {n} = {faces.lua_runs(p)},\n' for n, p in faces.GAZE.items())
            + '    spiral = {\n' + ''.join(f'      {faces.lua_runs(faces.mirror(f))},\n' for f in faces.spiral_frames()) + '    },\n'
            '  },\n  mouth = {\n'
            + ''.join(f'    {n} = {faces.lua_runs(faces.mirror(p))},\n' for n, p in faces.MOUTHS.items())
            + '  },\n}\n'
            '-- SPRITES END')

if __name__ == '__main__':
    p = sys.argv[1]; s = open(p).read()
    open(p, 'w').write(re.sub(r'-- SPRITES BEGIN.*?-- SPRITES END', lambda m: block(), s, flags=re.S))
