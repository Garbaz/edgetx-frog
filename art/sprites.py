def grid(s): return [r for r in s.strip('\n').split('\n')]
if __name__=='__main__':
    from PIL import Image, ImageDraw
    sp=[('awake',grid(AWAKE)),('asleep',grid(ASLEEP)),('pad',grid(PAD))]
    for n,g in sp: print(n, len(g[0]),'x',len(g), set(len(r) for r in g))
    sc=10; W=max(len(g[0]) for _,g in sp)+2; H=sum(len(g)+2 for _,g in sp)
    im=Image.new('RGB',(W*sc,H*sc),(178,196,170)); d=ImageDraw.Draw(im); y0=1
    for n,g in sp:
        for y,r in enumerate(g):
            for x,c in enumerate(r):
                if c not in '.': d.rectangle([(x+1)*sc,(y0+y)*sc,(x+2)*sc-1,(y0+y+1)*sc-1],fill=(40,44,52))
        y0+=len(g)+2
    im.save('sprites.png')
