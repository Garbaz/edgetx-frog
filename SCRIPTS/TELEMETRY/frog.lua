-- drone voltage (RxBt, 0.1 V steps) centred under the battery ("3.7V": 21 px under 19): the number in the mid font,
-- ink rows 53..62 with its bottom on the clock and timer digits' row, a small "V" 1 px after it, bottom-aligned
-- low battery: highlighted while the battery's fill shows, plain while it is hidden. The highlight is one box under
-- both fonts, exactly what the inverted mid-font text covers (a column either side, rows 52..63)
local function droneVoltage(v, low, t)
  local num = v and string.format("%.1f", v) or "--"
  local nw = inkWidth(num, "MID")
  local iw = v and nw + 1 + inkWidth("V", "SML") or nw
  local x = BX - 1 + (BW + 2 - iw) // 2
  local inv = (low and blinkOn(t)) and INVERS or 0
  if inv ~= 0 then lcd.drawFilledRectangle(x - 1, 52, iw + 2, 12, FORCE) end
  lcd.drawText(x, 52, num, MIDSIZE + inv)
  if v then lcd.drawText(x + nw + 1, 57, "V", SMLSIZE + inv) end
end

-- radio battery: symbol under the link meter (art/gauges.py), bottom on the clock digits' row 62;
-- returns whether it is low
local function radioBattery(t)
  local s = getGeneralSettings()
  local v = getValue("tx-voltage")
  local pct = clamp((v - s.battMin) / (s.battMax - s.battMin), 0, 1)
  local low = v < s.battWarn
  if low and not blinkOn(t) then return low end         -- flashes when the radio battery is low
  draw(RADIO_BATT, RADIO_X, RADIO_Y, FORCE)
  local fx, fy, fw, fh = RADIO_FILL[1], RADIO_FILL[2], RADIO_FILL[3], RADIO_FILL[4]
  local w = math.floor(fw * pct + 0.5)
  if w > 0 then lcd.drawFilledRectangle(RADIO_X + fx, RADIO_Y + fy, w, fh, FORCE) end
  return low
end

