  lcd.drawText(68, 56, string.format("%02d:%02d", secs // 60, secs % 60))    -- ink x 68..89
  draw(SPRITES.stopwatch, 92, 56, FORCE)
end

local vtx = { seq = 0, labels = {}, labelTries = {} }   -- index, at (tick of the last status reply), sent

-- MSP over CRSF: frame type 0x7A (request) / 0x7B (reply), flight controller 0xC8 <-> radio 0xEA, then a status byte
-- (bit 7 error, bit 4 first chunk, bits 5-6 MSP version 2, bits 0-3 sequence) and the MSPv2 header without $X< and
-- CRC: flags, command lo/hi, payload size lo/hi. Replies come in chunks of up to 58 bytes; all we read is in the first.
local function mspRequest(cmd, payload)
  local f = { 0xC8, 0xEA, 0x50 + vtx.seq, 0, cmd % 256, cmd // 256, #payload, 0 }
  for i, b in ipairs(payload) do f[8 + i] = b end
  if crossfireTelemetryPush(0x7A, f) then vtx.seq = (vtx.seq + 1) % 16 end
end

local function mspReplies(t)
  while true do
    local cmd, d = crossfireTelemetryPop()
    if cmd == nil then return end
    if cmd == 0x7B and d[1] == 0xEA and d[2] == 0xC8 and d[3] < 128 and (d[3] // 16) % 2 == 1 then
      local id, p = d[5] + d[6] * 256, 9                     -- p: first payload byte
      if id == MSP_DEVICE_STATUS and d[p + 5] == 1 then       -- type, ready, band/channel (3), power index known?
        vtx.index, vtx.at = d[p + 6], t
      elseif id == MSP_POWERLEVEL and d[p + 3] then           -- index, value (2), label length, label
        local label = ""
        for i = p + 4, p + 3 + d[p + 3] do
          if d[i] and d[i] > 32 then label = label .. string.char(d[i]) end
        end
        vtx.labels[d[p]] = label
      end
    end
  end
end

-- a missing label is asked for right after the status that named its index (up to 3 times), else the status
local function pollVtx(t, linked)
  local i = vtx.index
  local wantLabel = i and not vtx.labels[i] and (vtx.labelTries[i] or 0) < 3
  if linked and (vtx.sent == nil or t - vtx.sent >= (wantLabel and VTX_LABEL_RETRY or VTX_POLL)) then
    if wantLabel then
      mspRequest(MSP_POWERLEVEL, { i })
      vtx.labelTries[i] = (vtx.labelTries[i] or 0) + 1
    else
      mspRequest(MSP_DEVICE_STATUS, {})
    end
    vtx.sent = t
  end
  mspReplies(t)
end

-- VTX power, top left above the link meter: camera at x 1..8, the level 2 px right of it, both on rows 1..6
local VX, VY = 1, 1
local function vtxIndicator(t)
  local fresh = vtx.at and t - vtx.at < VTX_STALE
  draw(SPRITES.camera, VX, VY, FORCE)
  lcd.drawText(VX + #CAMERA[1] + 2, VY, fresh and (vtx.labels[vtx.index] or tostring(vtx.index)) or "--", SMLSIZE)
end

-- Betaflight sends the mode name, plus "*" (ready to arm) or "!" (arming blocked) while disarmed;
-- returns the name to show, armed, blocked, failsafe
local function parseMode(fm)
  if fm == "!FS!" then return "!FS!", true, false, true end
  local last = string.sub(fm, -1)
  if last == "*" or last == "!" then
    local name = string.sub(fm, 1, -2)
    return MODES[name] or name, false, last == "!", false
  end
  return MODES[fm] or fm, true, false, false
end

-- flight mode: a fixed 50 x 16 box, x 39..88 (centred on the screen axis x = 63.5, like the frog), y 37..52;
-- 3 px either side of the widest names (ANGLE, CHIRP: 42 px). The name is centred in it by its measured ink
-- (EdgeTX's CENTER counts the blank column after each glyph); an odd ink width can't be centred in the even box,
-- the spare pixel goes to the right, where each glyph's own spacing column is anyway.
local MB_X, MB_Y, MB_W, MB_H = 39, 37, 50, 16       -- 14 inner rows: even, like both ink heights
local INK = { MID = { flag = MIDSIZE, top = 1, h = 10 }, SML = { flag = SMLSIZE, top = 0, h = 6 } }
local function modeBox(name, filled, dotted)
  local font = (#name > 5) and "SML" or "MID"
  local iw, lead = inkWidth(name, font)
  local ink = INK[font]
  local tx = MB_X + 1 + (MB_W - 2 - iw) // 2 - lead
  local ty = MB_Y + 1 + (MB_H - 2 - ink.h) // 2 - ink.top
  if filled then
    roundRect(MB_X, MB_Y, MB_W, MB_H, "fill")
    lcd.drawText(tx, ty, name, ink.flag + INVERS)
  else
    roundRect(MB_X, MB_Y, MB_W, MB_H, dotted and "dots" or "line")   -- dotted box: arming blocked
    lcd.drawText(tx, ty, name, ink.flag)
  end
end

local FX, FY = 39, 1                -- frog position (50 x 32, centred on x = 63.5)

-- sleeping breath: 6 beats = 2.4 s; beats 0..2 breathing out, 3..5 breathing in
local function breath(t) return (t // BEAT) % 6 end

-- The flight, as the frog sees it. Two independent parts:
-- * the fly is driven by the drone alone, whatever the frog feels: it flies in from the side once the
--   armed drone's throttle goes above 15 % (alternating left and right) and circles the frog (behind it
--   on the back half of the orbit), the faster the more the drone tilts (tilt ~ speed). When the
--   throttle drops below 10 % or the drone disarms, an excited frog catches it with its tongue and gulps
--   it down; any other frog lets it fly away. (The gap between 10 and 15 % keeps a stick resting near
--   one of them from flickering.)
-- * the frog's hop: excited, it hops faster with the throttle (1.25..5 per second), 2 px high above half
--   throttle, still below 10 %; anxious and armed, it keeps bouncing 1 px, also at zero throttle.
local ORBIT_X, ORBIT_Y, ORBIT_RX, ORBIT_RY = 63.5, 15, 32, 14
local TONGUE_OUT, TONGUE_BACK, GULP = 12, 18, 60        -- ticks (10 ms)
local ENTER = 50                                       -- ticks for the fly to come in from / leave to the side
local THR_LOW, THR_HIGH = 0.10, 0.15                   -- throttle: fly stops below, comes above
local SIDE_X = { [-1] = 19, [1] = 104 }                -- where the fly appears / disappears
local hop = { phase = 0, height = 0 }
local fly = { state = "gone", side = 1 }               -- gone / entering / circling / leaving / caught
local flying = false                                   -- armed and throttle up (with the 10/15 % hysteresis)
local lastT

local function throttle()                               -- 0..1 from the throttle stick
  return clamp((getValue("thr") + 1024) / 2048, 0, 1)
end

local function orbitPos(a)                              -- top-left of the 5x3 fly sprite
  return math.floor(ORBIT_X + ORBIT_RX * math.cos(a) - 2 + 0.5), math.floor(ORBIT_Y + ORBIT_RY * math.sin(a) - 1 + 0.5)
end

local function flyAround() return fly.state == "entering" or fly.state == "circling" or fly.state == "leaving" end
local function gulped() return fly.state == "caught" and fly.timer >= TONGUE_OUT + TONGUE_BACK end

local function updateFly(dt, hunter)
  if fly.state == "caught" or fly.state == "leaving" or fly.state == "entering" then fly.timer = fly.timer + dt * 100 end
  if fly.state == "caught" and fly.timer >= TONGUE_OUT + TONGUE_BACK + GULP then fly.state = "gone" end
  if fly.state == "leaving" and fly.timer >= ENTER then fly.state = "gone" end
  if fly.state == "gone" and flying then
    fly.side = -fly.side
    fly.state, fly.timer, fly.angle = "entering", 0, (fly.side < 0) and math.pi or 0
  elseif (fly.state == "entering" or fly.state == "circling") and not flying then
    if hunter then fly.state = "caught"                -- throttle cut or disarm: snap!
    else fly.state, fly.from, fly.to = "leaving", fly.x, (fly.x < ORBIT_X) and SIDE_X[-1] or SIDE_X[1] end
    fly.timer, fly.behind = 0, false
  end
  if fly.state == "entering" or fly.state == "circling" then
    local tilt = math.sqrt(getValue("Ptch") ^ 2 + getValue("Roll") ^ 2)       -- radians
    local revs = 0.25 + 1.25 * clamp(tilt / 0.7, 0, 1)                         -- rounds per second
    if fly.state == "circling" then fly.angle = fly.angle + 2 * math.pi * revs * dt * ((fly.side < 0) and 1 or -1) end
    local ox, oy = orbitPos(fly.angle)
    if fly.state == "entering" then
      local f = clamp(fly.timer / ENTER, 0, 1)
      fly.x, fly.y = math.floor(SIDE_X[fly.side] + f * (ox - SIDE_X[fly.side]) + 0.5), oy
      if f >= 1 then fly.state = "circling" end
    else
      fly.x, fly.y = ox, oy
    end
    fly.behind = fly.state == "circling" and math.sin(fly.angle) < 0
  elseif fly.state == "leaving" then
    fly.x = math.floor(fly.from + clamp(fly.timer / ENTER, 0, 1) * (fly.to - fly.from) + 0.5)
  end
end

local function updateHop(dt, mood, armed, thr)
  local rate, height = 0, 0
  if mood == "excited" and flying then rate, height = 1.25 + 3.75 * thr, (thr > 0.5) and 2 or 1
  elseif mood == "anxious" and armed then rate, height = 1.25 + 3.75 * thr, 1 end
  hop.phase = (height > 0) and hop.phase + rate * dt or 0
  hop.height = height
end

local function tongue(x1, y1, y)                        -- 2 px wide, from the mouth
  local x0, y0 = 63, y + 13
  local n = math.max(math.abs(x1 - x0), math.abs(y1 - y0), 1)
  for i = 0, n do
    lcd.drawFilledRectangle(math.floor(x0 + (x1 - x0) * i / n + 0.5), math.floor(y0 + (y1 - y0) * i / n + 0.5), 2, 1, FORCE)
  end
  lcd.drawFilledRectangle(x1 - 1, y1 - 1, 3, 3, FORCE)  -- sticky tip
end

local function drawFly(t, x, y)
  draw(((t // 5) % 2 == 0) and SPRITES.flyUp or SPRITES.flyDown, x, y, FORCE)
end

-- the frog's mood, most urgent first:
--   asleep  no link                     eyes closed, breathing (wide mouth / open "o"), z's rising
--   dizzy   failsafe, link critical or  spiral eyes spinning, wobbly mouth
--           arming blocked
--   anxious something flashes: drone    wide eyes glancing at the side that flashes (right: drone battery,
--           or radio battery low, link  left: link meter or radio battery), clenched teeth, sweat drop;
--           weak                        bounces subtly while armed, ignores the fly
--   excited armed (or finishing a catch) open grin, hops with the throttle, eyes on the fly (only), catches it
--   resting disarmed                    eyes open, smiling
-- resting, excited and anxious blink every 4.8 s
-- anxious glances, on the frog's beat: one side flashing, a 0.3 s glance every 1.2 s; both sides, 0.4 s right and
-- 0.4 s left, each after 0.2 s at the pilot. right, left: whether something flashes on that side
local function glance(t, right, left)
  local c = t % 120
  if right and left then
    if c >= 20 and c < 60 then return FACE.eyes.glanceRight end
    if c >= 80 then return FACE.eyes.glanceLeft end
  elseif c >= 60 and c < 90 then
    return right and FACE.eyes.glanceRight or FACE.eyes.glanceLeft
  end
  return FACE.eyes.wide                                                     -- at the pilot
end

local function drawFrog(mood, t, right, left)
  local eyes, mouth = FACE.eyes.open, FACE.mouth.smile
  local y = FY + ((mood == "excited" or mood == "anxious") and hop.height > 0 and 2 or 0)   -- crouched to hop
          - ((hop.phase % 1 < 0.5) and hop.height or 0)
  local tip                                                                 -- tongue tip while catching
  if mood == "dizzy" then
    eyes, mouth = FACE.eyes.spiral[(t // (BEAT // 4)) % 4 + 1], FACE.mouth.wavy   -- one turn per beat
  elseif mood == "asleep" then
    eyes = FACE.eyes.closed
    mouth = (breath(t) < 3) and FACE.mouth.snore or FACE.mouth.wide            -- out: "o", in: wide
  elseif mood == "anxious" then
    eyes = glance(t, right, left)
    mouth = FACE.mouth.grimace
  elseif mood == "excited" then
    local L, R, C = FACE.eyes.lookLeft, FACE.eyes.lookRight, FACE.eyes.open
    mouth = FACE.mouth.grin
    eyes = C                                                                -- no fly: straight ahead
    if flyAround() then                                                     -- eyes on the fly
      eyes = (fly.x + 2 < 57) and L or (fly.x + 2 > 70) and R or C
    elseif fly.state == "caught" then
      eyes = (fly.x + 2 < 63) and L or R
      local f = fly.timer
      if f < TONGUE_OUT + TONGUE_BACK then
        local k = (f < TONGUE_OUT) and (f / TONGUE_OUT) or (1 - (f - TONGUE_OUT) / TONGUE_BACK)
        local tx, ty = fly.x + 2, fly.y + 1
        tip = { x = math.floor(63 + k * (tx - 63) + 0.5), y = math.floor((y + 13) + k * (ty - (y + 13)) + 0.5),
                withFly = f >= TONGUE_OUT }                                 -- on the way back
      else
        eyes, mouth = FACE.eyes.closed, FACE.mouth.smile                     -- gulp, eyes shut with delight
      end
    end
  end
  if (mood == "resting" or mood == "excited" or mood == "anxious") and not gulped() and (t % (12 * BEAT)) < 15 then
    eyes = FACE.eyes.blink                                                  -- 150 ms blink every 4.8 s
  end
  local showFly = flyAround() or (mood == "excited" and fly.state == "caught" and fly.timer < TONGUE_OUT)
  if showFly and fly.behind then drawFly(t, fly.x, fly.y) end               -- behind: the frog covers it
  draw(FROG_MASK, FX, y, ERASE)
  draw(FROG, FX, y, FORCE)
  draw(eyes, FX, y, FORCE)
  draw(mouth, FX, y, FORCE)
  if mood == "anxious" and t % 240 < 120 then                              -- sweat drop running straight down
    draw(SPRITES.sweat, FX + 37, y + 1 + (t % 240) // 20, FORCE)            -- the side of the head, touching it
  end
  if showFly and not fly.behind then drawFly(t, fly.x, fly.y) end
  if tip then
    tongue(tip.x, tip.y, y)
    if tip.withFly then drawFly(t, tip.x - 2, tip.y - 1) end
  end
  if mood == "asleep" then
    local b = breath(t)                       -- z's appear one by one while breathing out, fade while in
    if b <= 2 then draw(SPRITES.zSmall, FX + 41, FY + 10, FORCE) end
    if b >= 1 and b <= 3 then draw(SPRITES.zMid, FX + 45, FY + 5, FORCE) end
    if b >= 2 and b <= 4 then draw(SPRITES.zBig, FX + 50, FY, FORCE) end
  end
end

-- fm: the FM sensor (a string, or 0 when there is none)
local function frogAndMode(linked, fm, droneLow, radioLow, linkWeak, critical, t)
  local name, armed, blocked, failsafe = "NO LINK", false, false, false
  if type(fm) == "string" then name, armed, blocked, failsafe = parseMode(fm) end

  local right, left = droneLow, linkWeak or radioLow   -- something flashes on that side: the frog glances there
  local mood = not linked and "asleep" or (failsafe or critical or blocked) and "dizzy"
               or (right or left) and "anxious"
               or (armed or fly.state == "caught") and "excited" or "resting"
  if linked then
    local dt = lastT and clamp(t - lastT, 0, 20) / 100 or 0  -- seconds; capped when the screen was away
    local thr = throttle()
    lastT = t
    if not armed then flying = false
    elseif flying then flying = thr >= THR_LOW
    else flying = thr > THR_HIGH end
    updateFly(dt, mood == "excited")
    updateHop(dt, mood, armed, thr)
  else
    fly.state, flying, lastT, hop.phase, hop.height = "gone", false, nil, 0, 0
  end
  drawFrog(mood, t, right, left)
  modeBox(name, armed and not (failsafe and not blinkOn(t)), blocked)
end

-- Vibration for the alarm situations:
--   low drone voltage -> L01/SF1 in the model (RxBt < 3.6 V, repeats every 10 s)
--   link critical     -> EdgeTX's own "RF signal critical" alarm (RQly < 42, vibrates with haptic mode "no keys")
--   failsafe          -> here: FM is a text sensor, which logical switches cannot compare.
-- EdgeTX calls background() while this screen is not shown and run() while it is; both buzz.
local lastBuzz = -1000
local function buzzOnFailsafe(fm, t)
  if fm == "!FS!" and t - lastBuzz >= 6 * BEAT then    -- double buzz every 2.4 s
    playHaptic(40, 20)
    playHaptic(40, 0)
    lastBuzz = t
  end
end

local function background()
  if getRSSI() > 0 then buzzOnFailsafe(getValue("FM"), getTime()) end
end

local function run(event)
  local t = getTime()
  local rq, rqWarn, rqCrit = getRSSI()  -- RQly for ELRS/CRSF, 0 when no telemetry
  local linked = rq > 0
  local fm = linked and getValue("FM") or 0
  buzzOnFailsafe(fm, t)
  pollVtx(t, linked)

  local droneLow, pct, volts = false, nil, nil
  if linked then
    local v = getValue("RxBt")          -- 0 when Betaflight sees no battery (e.g. on USB; needs report_cell_voltage ON)
    if v > 0 then
      pct, volts = clamp(getValue("Bat%"), 0, 100), v
      droneLow = v < DRONE_LOW_V
    end
  end

  local tq = linked and getValue("TQly") or 0
  local linkWeak = linked and math.min(tq, rq) < rqWarn   -- the link meter flashes

  lcd.clear()
  linkWedge(tq, rq, linkWeak, t)
  droneBattery(pct, droneLow, t)
  droneVoltage(volts, droneLow, t)
  local radioLow = radioBattery(t)
  frogAndMode(linked, fm, droneLow, radioLow, linkWeak, linked and rq < rqCrit, t)
  vtxIndicator(t)
  clockAndTimer()
  return 0
end

return { run = run, background = background }
