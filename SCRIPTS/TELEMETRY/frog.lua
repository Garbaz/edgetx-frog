-- Betaflight sends the mode name, plus "*" (ready to arm) or "!" (arming blocked) while disarmed
local function parseMode(fm)
  if fm == "!FS!" then return "!FS!", true, false, true end
  local last = string.sub(fm, -1)
  if last == "*" or last == "!" then
    local name = string.sub(fm, 1, -2)
    return MODES[name] or name, false, last == "!", false
  end
  return MODES[fm] or fm, true, false, false
end

local function modeBox(name, filled, dotted)
  local font = (#name > 5) and "SML" or "MID"
  local iw, ink = inkWidth(name, font), INK[font]
  local w = math.max(48, iw + 8)
  if (w - 2 - iw) % 2 == 1 then w = w + 1 end
  local h = 16                                       -- 14 inner rows: even, like both ink heights
  local x, y = 64 - (w + 1) // 2, 37                 -- even w: centred on 63.5, odd w: on 63
  local tx = x + 1 + (w - 2 - iw) // 2
  local ty = y + 1 + (h - 2 - ink.h) // 2 - ink.top
  if filled then
    lcd.drawFilledRectangle(x, y, w, h, FORCE)
    lcd.drawText(tx, ty, name, ink.flag + INVERS)
  else
    if dotted then                                   -- dotted box: arming blocked
      for i = 0, w - 1, 2 do lcd.drawPoint(x + i, y, FORCE); lcd.drawPoint(x + i, y + h - 1, FORCE) end
      for j = 0, h - 1, 2 do lcd.drawPoint(x, y + j, FORCE); lcd.drawPoint(x + w - 1, y + j, FORCE) end
    else
      lcd.drawRectangle(x, y, w, h, FORCE)
    end
    lcd.drawText(tx, ty, name, ink.flag)
  end
end

local FX, FY = 39, 1                -- frog position (50 x 32, centred on x = 63.5)

-- sleeping breath: 6 beats = 2.4 s; beats 0..2 breathing out, 3..5 breathing in
local function breath(t) return (t // BEAT) % 6 end

-- armed: every 24 beats (9.6 s) a fly buzzes in, alternately from the left and the right; the frog
-- hops excitedly while it comes in, stares at it, keeps still to catch it with its tongue and gulps it down.
-- Beats 0..5 nothing, 6..15 fly flying in, 16 tongue out, 17 tongue back with the fly, 18..19 gulp.
local HUNT = 24
local function hunt(t)
  local cycle = t % (2 * HUNT * BEAT)
  local side = (cycle < HUNT * BEAT) and -1 or 1                    -- -1: fly on the left, 1: right
  local h = cycle % (HUNT * BEAT)                                   -- ticks into this hunt
  local function mx(x, w) return (side < 0) and x or (127 - x - (w or 0)) end
  if h < 6 * BEAT or h >= 20 * BEAT then return nil end
  local r = { side = side }
  if h < 16 * BEAT then                                             -- flying in on a wobbly path
    local p = (h - 6 * BEAT) / (10 * BEAT)
    r.fx, r.fy = mx(math.floor(19 + 17 * p + 0.5), 4), math.floor(7 + 4 * math.sin(p * 5 * math.pi) + 0.5)
    r.flying = true
  elseif h < 18 * BEAT then                                         -- tongue out to the fly, then back
    local f = (h < 17 * BEAT) and math.min(1, (h - 16 * BEAT) / 16) or (1 - (h - 17 * BEAT) / BEAT)
    local tx, ty = 63 + f * (mx(38) - 63), (FY + 13) + f * (8 - (FY + 13))
    r.tongue = { math.floor(tx + 0.5), math.floor(ty + 0.5) }
    if h < 16 * BEAT + 16 then r.fx, r.fy = mx(36, 4), 7               -- fly waits until the tongue arrives
    else r.fx, r.fy = r.tongue[1] - 2, r.tongue[2] - 1 end             -- then rides on the tip
  else
    r.gulp = true
  end
  return r
end

local function tongue(x1, y1)                                       -- 2 px wide, from the mouth
  local x0, y0 = 63, FY + 13
  local n = math.max(math.abs(x1 - x0), math.abs(y1 - y0), 1)
  for i = 0, n do
    local x, y = math.floor(x0 + (x1 - x0) * i / n + 0.5), math.floor(y0 + (y1 - y0) * i / n + 0.5)
    lcd.drawFilledRectangle(x, y, 2, 1, FORCE)
  end
  lcd.drawFilledRectangle(x1 - 1, y1 - 1, 3, 3, FORCE)               -- sticky tip
end

-- the frog's mood, most urgent first:
--   dizzy   failsafe or link critical   spiral eyes spinning, wobbly mouth
--   tired   drone battery low           heavy eyelids, yawns every 4.8 s
--   active  armed                       open grin, glancing left and right, bouncing; hunts flies
--   resting disarmed                    eyes open, smiling, blinks every 4.8 s
--   asleep  no link                     eyes closed, breathing (wide mouth / open "o"), z's rising
local function drawFrog(mood, t)
  local beat = t // BEAT
  local eyes, mouth, y = FACE.eyes.open, FACE.mouth.smile, FY
  if mood == "dizzy" then
    eyes, mouth = FACE.eyes.spiral[(t // (BEAT // 4)) % 4 + 1], FACE.mouth.wavy   -- one turn per beat
  elseif mood == "tired" then
    local b = beat % 12                                                     -- yawn in the last 4 of 12 beats
    eyes = (b == 9 or b == 10 or b == 11) and FACE.eyes.closed or FACE.eyes.tired
    mouth = (b == 9 or b == 10) and FACE.mouth.yawn2 or (b == 8 or b == 11) and FACE.mouth.yawn1 or FACE.mouth.neutral
  elseif mood == "asleep" then
    eyes = FACE.eyes.closed
    mouth = (breath(t) < 3) and FACE.mouth.snore or FACE.mouth.wide            -- out: "o", in: wide
  end
  local fly
  if mood == "active" then
    fly = hunt(t)
    local b = beat % 12                                                     -- look around: centre, left, centre, right
    eyes = (b == 4 or b == 5) and FACE.eyes.lookLeft or (b == 10 or b == 11) and FACE.eyes.lookRight or FACE.eyes.open
    mouth = FACE.mouth.grin
    y = FY + 1 - beat % 2                                                   -- bounce: 1 px up every other beat
    if fly then
      y = FY                                                                -- still for the catch and the gulp
      if fly.flying then                                                    -- excited: 2 px hops, twice as fast
        y = ((t // (BEAT // 2)) % 2 == 0) and FY + 2 or FY
      end
      eyes = (fly.side < 0) and FACE.eyes.lookLeft or FACE.eyes.lookRight  -- and stares at the fly
      if fly.gulp then eyes, mouth = FACE.eyes.closed, FACE.mouth.smile end -- gulp, eyes shut with delight
    end
  end
  if (mood == "resting" or mood == "active") and not (fly and fly.gulp) and (t % (12 * BEAT)) < 15 then
    eyes = FACE.eyes.blink                                                  -- 150 ms blink every 4.8 s
  end
  draw(FROG, FX, y, FORCE)
  draw(eyes, FX, y, FORCE)
  draw(mouth, FX, y, FORCE)
  if fly then
    if fly.tongue then tongue(fly.tongue[1], fly.tongue[2]) end
    if fly.fx then draw(((t // 5) % 2 == 0) and SPRITES.flyUp or SPRITES.flyDown, fly.fx, fly.fy, FORCE) end
  end
  if mood == "asleep" then
    local b = breath(t)                       -- z's appear one by one while breathing out, fade while in
    if b <= 2 then draw(SPRITES.zSmall, FX + 41, FY + 10, FORCE) end
    if b >= 1 and b <= 3 then draw(SPRITES.zMid, FX + 45, FY + 5, FORCE) end
    if b >= 2 and b <= 4 then draw(SPRITES.zBig, FX + 50, FY, FORCE) end
  end
end

local function frogAndMode(linked, low, critical)
  local fm = linked and getValue("FM") or 0
  local name, armed, blocked, failsafe = "NO LINK", false, false, false
  if type(fm) == "string" then name, armed, blocked, failsafe = parseMode(fm) end

  local mood = not linked and "asleep" or (failsafe or critical) and "dizzy" or low and "tired"
               or armed and "active" or "resting"
  drawFrog(mood, getTime())
  modeBox(name, armed and not (failsafe and not blinkOn()), blocked)
end

-- Vibration for the alarm situations:
--   low drone voltage -> L01/SF1 in the model (RxBt < 3.6 V, repeats every 10 s)
--   link critical     -> EdgeTX's own "RF signal critical" alarm (RQly < 42, vibrates with haptic mode "no keys")
--   failsafe          -> here: FM is a text sensor, which logical switches cannot compare.
-- EdgeTX calls background() while this screen is not shown; run() calls it while it is.
local lastBuzz = -1000
local function background()
  if getRSSI() > 0 and getValue("FM") == "!FS!" then
    local t = getTime()
    if t - lastBuzz >= 6 * BEAT then      -- double buzz every 2.4 s
      playHaptic(40, 20)
      playHaptic(40, 0)
      lastBuzz = t
    end
  end
end

local function run(event)
  background()
  lcd.clear()
  local rq, rqWarn, rqCrit = getRSSI()  -- RQly for ELRS/CRSF, 0 when no telemetry
  local linked = rq > 0
  linkWedge(linked and getValue("TQly") or 0, rq, rqWarn)

  local pct, low = nil, false
  if linked then
    pct = clamp(getValue("Bat%"), 0, 100)
    local v = getValue("RxBt")
    low = v > 0 and v < DRONE_LOW_V
  end
  droneBattery(pct, low)
  percent(pct, low)
  frogAndMode(linked, low, linked and rq < rqCrit)
  radioBattery()
  times()
  return 0
end

return { run = run, background = background }
